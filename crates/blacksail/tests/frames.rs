//! Seal screens of the tests (2560×1600, 繁體 client) as RapidOCR reads them (fixtures/*.tsv, made by
//! dev/ocr_dump.py): Windows' reader is not on Linux, and RapidOCR misreads more (賣藏 for 寶藏, 遥摆 for 請選擇),
//! so what reads right here should on Windows too. The first test's (17:29-17:30) and the second's (18:05-18:10),
//! where 0.2.1 read many cards wrong: a white card's title unread merged its text with its neighbour's.

use blacksail::cards::{cards, Line, Word};

/// A fixture's lines, each split into a word per character or number, as Windows reads Chinese.
fn lines(name: &str) -> Vec<Line> {
    lines_with(name, 0.0)
}

/// As `lines`, with `space` times the text's height of room before and after each number: as Windows read small
/// text in the fifth test, a line in parts at the spaces around its numbers.
fn lines_with(name: &str, space: f32) -> Vec<Line> {
    let text = std::fs::read_to_string(format!("{}/fixtures/{name}.tsv", env!("CARGO_MANIFEST_DIR"))).unwrap();
    let mut out = Vec::new();
    for l in text.lines().filter(|l| !l.starts_with('#')) {
        let f: Vec<&str> = l.split('\t').collect();
        let (x, y, w, h): (f32, f32, f32, f32) = (f[1].parse().unwrap(), f[2].parse().unwrap(), f[3].parse().unwrap(), f[4].parse().unwrap());
        // digits stay together, other characters one by one
        let mut words: Vec<String> = Vec::new();
        for c in f[0].chars() {
            match words.last_mut() {
                Some(last) if c.is_ascii_digit() && last.chars().all(|d| d.is_ascii_digit()) => last.push(c),
                _ => words.push(c.to_string()),
            }
        }
        let n: usize = words.iter().map(|w| w.chars().count()).sum();
        let digits = |t: &str| t.chars().all(|c| c.is_ascii_digit());
        // the room is within the line as read (its characters narrower), a space at most 6% of the line
        let space_px = (space * h).min(0.06 * w);
        let rooms = words.iter().filter(|t| digits(t)).count() as f32 * 2.0 * space_px;
        let cw = (w - rooms) / n as f32;
        let mut cx = x;
        out.push(
            words
                .into_iter()
                .map(|t| {
                    let ww = cw * t.chars().count() as f32;
                    let room = if digits(&t) { space_px } else { 0.0 };
                    cx += room;
                    let word = Word { text: t, x: cx, y, w: ww * 0.9, h };
                    cx += ww + room;
                    word
                })
                .collect(),
        );
    }
    out
}

/// Each card's category and seal, as read.
fn read(name: &str) -> Vec<(String, String)> {
    read_with(name, 0.0)
}

/// The screen's size, from the fixture's first line ("# 2560x1440").
fn size(name: &str) -> (f32, f32) {
    let text = std::fs::read_to_string(format!("{}/fixtures/{name}.tsv", env!("CARGO_MANIFEST_DIR"))).unwrap();
    let head = text.lines().next().unwrap().trim_start_matches('#').trim().to_string();
    let (w, h) = head.split_once('x').unwrap();
    (w.parse().unwrap(), h.parse().unwrap())
}

fn read_with(name: &str, space: f32) -> Vec<(String, String)> {
    let (w, h) = size(name);
    cards(&lines_with(name, space), w, h).iter().map(|c| (c.category.unwrap_or("?").to_string(), c.seal(None).map_or("?".into(), |s| s.text.clone()))).collect()
}

/// Read right both as whole lines and as lines in parts at their numbers.
fn expect(name: &str, want: [(&str, &str); 3]) {
    let want: Vec<(String, String)> = want.iter().map(|(c, t)| (c.to_string(), t.to_string())).collect();
    assert_eq!(read(name), want, "{name}");
    assert_eq!(read_with(name, 1.6), want, "{name} in parts");
}

